import { expect, test } from "@playwright/test";

test("award focus is temporary and rotation keeps the province open", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  const map = page.locator(".map-canvas");
  await expect(map).toHaveAttribute("data-landing", "settled");
  const home = await map.getAttribute("data-camera-target");
  const angle = await map.getAttribute("data-camera-angle");
  const mali = page.getByRole("button", { name: "Mock Mali", exact: true });
  await mali.press("Enter");
  await expect(page.locator(".recipient-bubble[data-recipient-id]")).toHaveCount(1);
  await expect(map).not.toHaveAttribute("data-camera-target", home!);
  const focus = (await map.getAttribute("data-camera-target"))!;
  await page.mouse.move(100, 500);
  await page.mouse.down();
  await page.mouse.move(160, 500, { steps: 5 });
  await page.mouse.up();
  await expect(mali).toHaveAttribute("aria-pressed", "true");
  await expect(map).toHaveAttribute("data-camera-target", focus);
  await expect(map).not.toHaveAttribute("data-camera-angle", angle!);
  await page.keyboard.press("Escape");
  await expect(mali).toBeFocused();
  await expect(mali).toHaveAttribute("aria-pressed", "false");
  await expect(map).toHaveAttribute("data-camera-target", home!);
});

for (const width of [320, 390, 1440]) {
  test(`drag and touch adjust both orbit axes while zoom and resize preserve the pivot at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 });
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.goto("/");
    const map = page.locator(".map-canvas");
    await expect(map).toHaveAttribute("data-landing", "settled");
    const homeTarget = (await map.getAttribute("data-camera-target"))!;
    const tilt = (await map.getAttribute("data-camera-tilt"))!;
    const angle = await map.getAttribute("data-camera-angle");
    await page.getByRole("button", { name: "Mock Mali", exact: true }).press("Enter");
    const target = (await map.getAttribute("data-camera-target"))!;
    await page.mouse.move(50, 600);
    await page.mouse.down();
    await page.mouse.move(100, 640, { steps: 5 });
    await page.mouse.up();
    await expect(map).not.toHaveAttribute("data-camera-angle", angle!);
    await expect(map).not.toHaveAttribute("data-camera-tilt", tilt);
    await expect(map).toHaveAttribute("data-selected-province", "TH-10");
    await page.mouse.wheel(0, -250);
    await expect.poll(async () => Number(await map.getAttribute("data-camera-zoom"))).toBeGreaterThan(1);
    const session = await page.context().newCDPSession(page);
    await session.send("Emulation.setTouchEmulationEnabled", { enabled: true, maxTouchPoints: 2 });
    const beforeTouch = await map.getAttribute("data-camera-angle");
    const beforeTouchTilt = (await map.getAttribute("data-camera-tilt"))!;
    await session.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: 55, y: 600, id: 1 }] });
    await session.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: 105, y: 570, id: 1 }] });
    await session.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await expect(map).not.toHaveAttribute("data-camera-angle", beforeTouch!);
    await expect(map).not.toHaveAttribute("data-camera-tilt", beforeTouchTilt);
    await session.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: 80, y: 600, id: 1 }, { x: 130, y: 600, id: 2 }] });
    await session.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: 55, y: 600, id: 1 }, { x: 155, y: 600, id: 2 }] });
    await session.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await session.detach();
    await expect(map).toHaveAttribute("data-camera-target", target);
    const adjustedTilt = (await map.getAttribute("data-camera-tilt"))!;
    const zoom = Number(await map.getAttribute("data-camera-zoom"));
    expect(zoom).toBeGreaterThan(1);
    expect(zoom).toBeLessThanOrEqual(2.5);
    await page.setViewportSize({ width: width === 1440 ? 1200 : width + 10, height: 800 });
    await expect(map).toHaveAttribute("data-camera-target", target);
    await expect(map).toHaveAttribute("data-camera-tilt", adjustedTilt);
    await expect(page.locator(".recipient-bubble[data-recipient-id]")).toHaveCount(1);
    await page.keyboard.press("Escape");
    await expect(map).toHaveAttribute("data-camera-target", homeTarget);
    await expect(map).toHaveAttribute("data-camera-zoom", "1.00000");
    await expect(page.locator(".award-discovery")).toHaveCount(0);
  });
}

test("zoom remains bounded and Back restores the saved overview", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  const map = page.locator(".map-canvas");
  const south = page.getByRole("button", { name: "Mock Ploy", exact: true });
  await expect(south).toBeVisible();
  const target = await map.getAttribute("data-camera-target");
  await south.press("Enter");
  await page.mouse.move(200, 400);
  for (let step = 0; step < 8; step++) await page.mouse.wheel(0, -400);
  await expect(map).toHaveAttribute("data-camera-zoom", "2.50000");
  await expect(page.locator(".recipient-bubble[data-recipient-id]")).toHaveCount(1);
  await page.keyboard.press("Escape");
  await expect(page.locator(".award-discovery")).toHaveCount(0);
  await expect(south).toBeFocused();
  await expect(map).toHaveAttribute("data-camera-target", target!);
  await expect(map).toHaveAttribute("data-camera-zoom", "1.00000");
  for (let step = 0; step < 8; step++) await page.mouse.wheel(0, 400);
  expect(Number(await map.getAttribute("data-camera-zoom"))).toBeGreaterThanOrEqual(0.75);
});

test("medal taps enter a province once and land taps do not open a panel", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  const medal = page.getByRole("button", { name: "Mock Mali", exact: true });
  await medal.click();
  await expect(page.locator(".recipient-bubble[data-recipient-id]")).toHaveCount(1);
  await medal.click();
  await expect(page.locator(".recipient-bubble[data-recipient-id]")).toHaveCount(1);
  await page.locator(".recipient-bubble[data-recipient-id]").press("Enter");
  await expect(page.locator(".student-competition").first()).toContainText("Creative Coding");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await page.locator("canvas").click({ position: { x: 50, y: 190 } });
  await expect(page.locator(".award-discovery")).toHaveCount(0);
});
